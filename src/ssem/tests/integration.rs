//! End-to-end tests: load a full 32-word store, run the machine, and
//! compare the resulting store (and registers) with the expected end
//! state. Each store is given as its non-zero words only, as 32 bits in
//! SSEM order (least significant bit first).

use super::store_from_bits;
use crate::ssem::simulator::Simulator;

/// Run `cycles` cycles on a simulator built from `start` and assert its
/// store equals the one built from `end`. Returns the simulator for
/// register assertions.
fn run_and_assert_store(start: &[(usize, &str)], end: &[(usize, &str)], cycles: u32) -> Simulator {
    let mut sim = Simulator::from(store_from_bits(start));
    sim.run(cycles);
    let expected = Simulator::from(store_from_bits(end));
    assert_eq!(sim.store, expected.store);
    sim
}

#[test]
fn integration_test_all() {
    let start: &[(usize, &str)] = &[
        (0, "10000000000000000000000000000000"),
        (1, "01010000000000100000000000000000"),
        (2, "00000000000000010000000000000000"),
        (3, "00001000000001100000000000000000"),
        (4, "00000000000000110000000000000000"),
        (6, "00000000000001000000000000000000"),
        (8, "00000000000001110000000000000000"),
        (10, "00000111111111111111111111111111"),
    ];
    let mut end = start.to_vec();
    end.push((16, "11111111111111111111111111111111"));
    run_and_assert_store(start, &end, 300);
}

